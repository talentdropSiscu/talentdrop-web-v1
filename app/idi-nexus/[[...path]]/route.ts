import { NextRequest, NextResponse } from "next/server";

export const runtime = "nodejs";
export const dynamic = "force-dynamic";

/**
 * Proxy limitado a la web corporativa IDI NEXUS.
 * Mantiene páginas y recursos bajo /idi-nexus sin tocar las rutas de TalentDrop.
 * IDI_NEXUS_ORIGIN debe ser un dominio HTTPS de origen accesible desde Vercel.
 */
type Params = { params: Promise<{ path?: string[] }> };
const prefix = "/idi-nexus";
const allowed = /^(?:\/|\/(?:es|_astro|img|video|brand|assets|fonts|favicon\.svg|favicon\.ico|robots\.txt)(?:\/|$))/;

function origin(): string | null {
  const raw = "https://pnexus-web-git-design-b-correcciones-visuales-talent-drop-team.vercel.app";
  if (!raw) return null;
  try {
    const url = new URL(raw);
    if (url.protocol !== "https:" || url.username || url.password || (url.pathname !== "/" && url.pathname !== "") || url.search || url.hash) return null;
    return url.origin;
  } catch { return null; }
}

function rewriteHtml(body: string): string {
  return body
    // Absolute resource and navigation URLs generated by the Astro site.
    .replace(/(\b(?:href|src|poster|action)=["'])\/(?!\/)/gi, `$1${prefix}/`)
    .replace(/(\b(?:content)=["'])(\/[^"']*)(["'])/gi, (_, a, value, end) => `${a}${prefix}${value}${end}`)
    .replace(/(\b(?:srcset)=["'])([^"']+)(["'])/gi, (_, a, value, end) => a + value.replace(/(^|,\s*)\/(?!\/)/g, `$1${prefix}/`) + end)
    // Canonical URL should reflect the public destination, not the origin.
    .replace(/(<link[^>]+rel=["']canonical["'][^>]*href=["'])[^"']+/gi, "$1https://www.talentdrop.es/idi-nexus/");
}

async function handle(req: NextRequest, { params }: Params): Promise<NextResponse> {
  const upstream = origin();
  if (!upstream) return new NextResponse("Ruta IDI NEXUS todavía no configurada", { status: 503 });
  const { path = [] } = await params;
  const pathname = path.length ? "/" + path.join("/") : "/es/";
  if (!allowed.test(pathname) || path.some(x => x === ".." || x.includes("\\"))) {
    return new NextResponse("Ruta no admitida", { status: 404 });
  }
  // Astro publica las páginas como directorios y exige barra final.
  // Resolverla en el origen evita el bucle de redirecciones con Next.js.
  const isAsset = /\\.[a-z0-9]{2,8}$/i.test(pathname);
  const canonicalPath = !isAsset && !pathname.endsWith("/") ? pathname + "/" : pathname;
  let target = new URL(canonicalPath + req.nextUrl.search, upstream);
  try {
    let r: Response | undefined;
    // Seguir únicamente redirecciones internas del origen, nunca reenviar
    // al visitante un 308 que pueda entrar en conflicto con Next.js.
    for (let hop = 0; hop < 5; hop++) {
      r = await fetch(target, {
        method: req.method,
        redirect: "manual",
        cache: "no-store",
        headers: { accept: req.headers.get("accept") || "*/*" },
        signal: AbortSignal.timeout(12000),
      });
      if (r.status < 300 || r.status >= 400) break;
      const location = r.headers.get("location");
      if (!location) break;
      const dest = new URL(location, target);
      if (dest.origin !== upstream) return new NextResponse("Redirección externa no admitida", { status: 502 });
      if (dest.href === target.href) return new NextResponse("Bucle de redirección en origen", { status: 502 });
      target = dest;
    }
    if (!r || (r.status >= 300 && r.status < 400)) return new NextResponse("Redirección de origen no resuelta", { status: 502 });
    const type = r.headers.get("content-type") || "application/octet-stream";
    const headers = new Headers({ "content-type": type, "cache-control": "no-store", "x-content-type-options": "nosniff" });
    if (req.method === "HEAD") return new NextResponse(null, { status: r.status, headers });
    if (type.includes("text/html")) {
      const html = rewriteHtml(await r.text());
      return new NextResponse(html, { status: r.status, headers });
    }
    return new NextResponse(r.body, { status: r.status, headers });
  } catch {
    return new NextResponse("Origen de IDI NEXUS inaccesible", { status: 502 });
  }
}

export async function GET(req: NextRequest, ctx: Params) { return handle(req, ctx); }
export async function HEAD(req: NextRequest, ctx: Params) { return handle(req, ctx); }
